type NameResult struct {
	Name   string `json:"name"`
	Gender int    `json:"gender"`
	Avatar string `json:"avatar"`
}

func RandomName() NameResult {
	// 1. 随机性别 (0:男, 1:女)
	genderCode := rng.Intn(2)
	male := genderCode == 0

	// 设置返回的性别值 (1:男, 2:女)
	gender := 1
	nameLib := boyName
	if !male {
		nameLib = girlName
		gender = 2
	}

	// 2. 随机字数 2 或 3
	size := 2 + rng.Intn(2) // 2 or 3

	// 3. 拼名字
	family := surname[rng.Intn(len(surname))]

	// 处理复姓情况：如果是复姓且选择3字名，实际会成为4个字
	// 这里可以根据需要调整逻辑，比如复姓时只生成2字名
	var name string
	if size == 2 {
		name = family + nameLib[rng.Intn(len(nameLib))]
	} else {
		name = family + nameLib[rng.Intn(len(nameLib))] + nameLib[rng.Intn(len(nameLib))]
	}

	return NameResult{
		Name:   name,
		Gender: gender,
		Avatar: fmt.Sprintf("https://api.dicebear.com/7.x/avataaars/svg?seed=%s", name),
	}
}
